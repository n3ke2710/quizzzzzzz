// All special kinds appear in the demo; the rest of the cells remain ordinary questions.
const specials: Record<string, CellKind> = {
  '0-0-3': 'cat', '0-1-2': 'approx', '0-2-1': 'shield', '0-3-3': 'retry',
  '0-4-2': 'retry', '1-0-2': 'doubleReward', '1-1-3': 'swap', '1-2-2': 'double',
  '1-3-1': 'flip', '1-4-3': 'doubleReward',
};

function makePack(blank: boolean): QuizPack {
  const prefix = blank ? 'blank' : 'demo';
  const rounds = [roundOne, roundTwo].map((categories, roundIndex) => ({
    id: `${prefix}-round-${roundIndex + 1}`,
    title: `${roundIndex + 1}-й раунд`,
    categories: categories.map(([title, items], categoryIndex) => ({
      id: `${prefix}-r${roundIndex + 1}-c${categoryIndex + 1}`,
      title: blank ? `Категория ${categoryIndex + 1}` : title,
      questions: items.map(([text, answer], questionIndex) => ({
        id: `${prefix}-r${roundIndex + 1}-c${categoryIndex + 1}-q${questionIndex + 1}`,
        value: (questionIndex + 1) * (roundIndex + 1) * 100,
        kind: blank ? 'normal' as const : specials[`${roundIndex}-${categoryIndex}-${questionIndex}`] ?? 'normal',
        prompt: { text: blank ? '' : text },
        answer: { text: blank ? '' : answer },
      })),
    })),
  })) as QuizPack['rounds'];
  return {
    version: 1,
    id: `${prefix}-quiz`,
    title: blank ? 'Моя игра' : 'Своя игра · Вечер друзей',
    rounds,
    final: finalTrivia.map(([title, text, answer], index) => ({
      id: `${prefix}-final-${index + 1}`,
      title: blank ? `Тема ${index + 1}` : title,
      prompt: { text: blank ? '' : text },
      answer: { text: blank ? '' : answer },
    })),
  };
}

export function createDemoPack(): QuizPack { return makePack(false); }
export function createBlankPack(): QuizPack { return makePack(true); }
